<?php

namespace App\Console;

use Illuminate\Console\Command;
use Illuminate\Routing\Route;
use Illuminate\Support\Facades\Route as Router;
use Illuminate\Support\Str;

/**
 * Generates docs/openapi.json from the live route table so the endpoint inventory can never drift from the code.
 * Request/response conventions are described in docs/05-api-specification.md; CI fails if this file is stale.
 */
class OpenApiCommand extends Command
{
    protected $signature = 'docs:openapi {--check : Fail if the committed file is out of date}';

    protected $description = 'Generate the OpenAPI 3.1 path inventory from registered API routes';

    public function handle(): int
    {
        $paths = [];
        foreach (Router::getRoutes() as $route) {
            /** @var Route $route */
            if (! str_starts_with($route->uri(), 'api/') || str_starts_with($route->uri(), 'api/broadcasting')) {
                continue;
            }
            $uri = '/'.$route->uri();
            $middleware = $route->gatherMiddleware();
            $plane = match (true) {
                str_starts_with($uri, '/api/platform') => 'Platform',
                str_starts_with($uri, '/api/patient') => 'Patient app',
                str_starts_with($uri, '/api/public') => 'Public',
                default => 'Staff',
            };
            $controller = class_basename(Str::before((string) $route->getActionName(), '@'));
            foreach ($route->methods() as $method) {
                if ($method === 'HEAD') {
                    continue;
                }
                $op = [
                    'tags' => [$plane.' · '.Str::of($controller)->replace('Controller', '')->headline()],
                    'operationId' => Str::camel(strtolower($method).' '.str_replace(['/', '{', '}', '-'], ' ', Str::after($route->uri(), 'api/'))),
                    'responses' => ['200' => ['description' => 'OK — {"data": ...}'], '4XX' => ['$ref' => '#/components/responses/Error']],
                ];
                $params = array_map(fn ($p) => ['name' => $p, 'in' => 'path', 'required' => true, 'schema' => ['type' => 'string']], $route->parameterNames());
                if ($params) {
                    $op['parameters'] = $params;
                }
                if (in_array('auth:sanctum', $middleware, true)) {
                    $op['security'] = [['bearer' => []]];
                }
                $perms = collect($middleware)->filter(fn ($m) => is_string($m) && str_starts_with($m, 'can:'))->map(fn ($m) => Str::after($m, 'can:'))->values()->all();
                $features = collect($middleware)->filter(fn ($m) => is_string($m) && str_starts_with($m, 'feature:'))->map(fn ($m) => Str::after($m, 'feature:'))->values()->all();
                if ($perms || $features) {
                    $op['description'] = trim(($perms ? 'Requires permission: '.implode(', ', $perms).'. ' : '').($features ? 'Plan feature: '.implode(', ', $features).'.' : ''));
                }
                $paths[$uri][strtolower($method)] = $op;
            }
        }
        ksort($paths);

        $doc = [
            'openapi' => '3.1.0',
            'info' => ['title' => 'EasyHealthcare API', 'version' => '1.0.0', 'description' => 'Generated by `php artisan docs:openapi`. Conventions: docs/05-api-specification.md.'],
            'servers' => [['url' => '/']],
            'components' => [
                'securitySchemes' => ['bearer' => ['type' => 'http', 'scheme' => 'bearer']],
                'responses' => ['Error' => ['description' => 'Error envelope', 'content' => ['application/json' => ['schema' => [
                    'type' => 'object', 'properties' => ['error' => ['type' => 'object', 'properties' => ['code' => ['type' => 'string'], 'message' => ['type' => 'string'], 'fields' => ['type' => 'object']]]],
                ]]]]],
            ],
            'paths' => $paths,
        ];
        $json = json_encode($doc, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE)."\n";
        $file = base_path('../docs/openapi.json');

        if ($this->option('check')) {
            if (! is_file($file) || file_get_contents($file) !== $json) {
                $this->error('docs/openapi.json is out of date. Run php artisan docs:openapi.');

                return self::FAILURE;
            }
            $this->info('OpenAPI inventory is up to date.');

            return self::SUCCESS;
        }
        file_put_contents($file, $json);
        $this->info(count($paths).' paths written to docs/openapi.json');

        return self::SUCCESS;
    }
}
